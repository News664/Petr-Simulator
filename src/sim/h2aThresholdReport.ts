/**
 * Markdown renderer for the H2A threshold calibration.
 *
 * Separate from `report.ts` and from the Phase 1.1 experiment renderer on
 * purpose: this run must not repurpose or overwrite the historical Phase 1.1
 * report, and its telemetry is H2A-specific.
 *
 * The document reports measurements and mechanically checks each arm against
 * the review bands in the supplied plan. It does not select a profile, and the
 * written recommendation lives in the findings document it links to.
 */

export interface H2aArm {
  /** CURRENT_AUTHORED / LOW / MID / HIGH. */
  label: string;
  mode: string;
  note?: string;
  contentVersion: string;
  /** Null for the untouched control arm. */
  gatesRewritten: number | null;
  appliedThresholds: Record<string, number> | null;
  eventsWithoutGate: string[];
  metrics: MetricsSummary;
  factions: FactionSummary;
  telemetry: H2aArmTelemetry;
}

export interface H2aThresholdPayload {
  generatedAt: string;
  /** Fingerprint of the canonical corpus, before any reversible rewrite. */
  contentVersion: string;
  balanceVersion: string;
  matrixVersion: string;
  planVersion: string;
  planStatus: string;
  planPurpose: string;
  baseCorpus: string;
  baseSeed: string;
  runsPerArm: number;
  sampling: Record<string, string | number | boolean>;
  arms: H2aArm[];
  requiredCoreMetrics: string[];
  explicitlyNotRun: string[];
  retentionPolicy: { notDropped: boolean; note: string };
  methodologyNotes: string[];
}

const BUCKETS = ['18-24', '25-34', '35-44', '45-54', '55-64', '65+'] as const;

function bucketShare(metrics: MetricsSummary, band: string): number | null {
  const entry = metrics.endingAgeShareByTargetBucket.find((b) => b.band === band);
  return entry ? entry.observedShare : null;
}

function snapshot(telemetry: H2aArmTelemetry, label: string): StatSnapshot | undefined {
  return telemetry.statSnapshots.find((s) => s.label === label);
}

function shareAtLeast15(telemetry: H2aArmTelemetry, label: string, stat: VisibleStat): number | null {
  const found = snapshot(telemetry, label);
  return found ? found.byStat[stat].shareAtLeast15 : null;
}

function drift(telemetry: H2aArmTelemetry, label: string, stat: VisibleStat): number | null {
  const found = snapshot(telemetry, label);
  return found ? found.byStat[stat].meanDriftFromStart : null;
}

function largestBucket(metrics: MetricsSummary): string {
  let best = '—';
  let bestShare = -1;
  for (const band of BUCKETS) {
    const value = bucketShare(metrics, band) ?? 0;
    if (value > bestShare) {
      bestShare = value;
      best = band;
    }
  }
  return best;
}

/** Mechanical check of one arm against the plan's stated review bands. */
function reviewBandFlags(arm: H2aArm): string[] {
  const m = arm.metrics;
  const flags: string[] = [];
  const completion = m.completedRate;
  if (completion < 0.45) flags.push(`completion ${pct(completion)} below the 45–70% review band`);
  else if (completion > 0.7) flags.push(`completion ${pct(completion)} above the 45–70% review band`);
  const commitment = m.materialCommitmentRate;
  if (commitment < 0.45) flags.push(`commitment ${pct(commitment)} below the 45–70% review band`);
  else if (commitment > 0.7) flags.push(`commitment ${pct(commitment)} above the 45–70% review band`);
  const commitAge = arm.telemetry.commitmentTiming.mean;
  if (commitAge !== null && commitAge > 35) {
    flags.push(`mean commitment age ${num(commitAge)} above the early-30s preference`);
  }
  if (largestBucket(m) !== '25-34') flags.push(`largest ending bucket is ${largestBucket(m)}, not 25-34`);
  if (m.endingShare65Plus > 0.35) flags.push(`65+ still holds ${pct(m.endingShare65Plus)} of endings`);
  const factionShare = arm.factions.factionEndingShare;
  if (factionShare > 0.5) flags.push(`faction endings are ${pct(factionShare)} of completions`);
  const failures = m.guardrails.filter((g) => g.severity === 'failure');
  if (failures.length > 0) flags.push(`${failures.length} guardrail failure(s)`);
  return flags;
}

