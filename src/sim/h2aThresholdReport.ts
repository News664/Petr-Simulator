  // -------------------------------------------------------------------------
  out.push('## 7. Low-stat conditional risk');
  out.push('');
  out.push(
    'Person-year analysis from age 18. Each observed year is classified by the stat value **entering** that year, ' +
      'then followed forward. A person-year counts toward a horizon only when its follow-up is complete: the run ' +
      'either reached an ending, or was still being simulated at `age + horizon`. Person-years censored by the ' +
      'diagnostic maximum age are dropped rather than counted as "no event". Commitment and faction-COMMITTED ' +
      'probabilities are conditioned on that outcome not having happened yet, so their denominators differ.',
  );
  out.push('');
  out.push('**This is correlation, not causation, and no danger weighting is implemented.**');
